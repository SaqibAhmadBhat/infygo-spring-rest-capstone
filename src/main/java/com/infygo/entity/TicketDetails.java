package com.infygo.entity;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;

import org.springframework.data.domain.Persistable;

/**
 * Maps the prescribed Ticket_Details table. The PNR is the primary key and is generated by the application.
 * Persistable guarantees an INSERT (never a merge) so a PNR collision fails instead of overwriting a ticket.
 */
@Entity
@Table(name = "Ticket_Details")
public class TicketDetails implements Persistable<Integer> {

    @Id
    @Column(name = "pnr")
    private Integer pnr;

    @Column(name = "booking_date", nullable = false)
    private LocalDate bookingDate;

    @Column(name = "departure_date", nullable = false)
    private LocalDate departureDate;

    @Column(name = "departure_time", nullable = false, length = 5)
    private String departureTime;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "flight_id", nullable = false)
    private FlightDetails flight;

    @Column(name = "no_of_seats", nullable = false)
    private Integer noOfSeats;

    @Column(name = "total_fare", nullable = false, precision = 10, scale = 2)
    private BigDecimal totalFare;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private UserDetails user;

    @OneToMany(mappedBy = "ticket", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("passengerId ASC")
    private List<PassengerDetails> passengers = new ArrayList<>();

    @Transient
    private boolean newEntity = true;

    protected TicketDetails() {
    }

    public TicketDetails(Integer pnr, LocalDate bookingDate, FlightDetails flight, UserDetails user,
                         Integer noOfSeats, BigDecimal totalFare) {
        this.pnr = pnr;
        this.bookingDate = bookingDate;
        this.flight = flight;
        this.user = user;
        this.departureDate = flight.getFlightAvailableDate();
        this.departureTime = flight.getDepartureTime();
        this.noOfSeats = noOfSeats;
        this.totalFare = totalFare;
    }

    /** Keeps both sides of the ticket-passenger association in sync. */
    public void addPassenger(PassengerDetails passenger) {
        passenger.setTicket(this);
        passengers.add(passenger);
    }

    @Override
    public Integer getId() {
        return pnr;
    }

    @Override
    public boolean isNew() {
        return newEntity;
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.newEntity = false;
    }

    public Integer getPnr() {
        return pnr;
    }

    public LocalDate getBookingDate() {
        return bookingDate;
    }

    public LocalDate getDepartureDate() {
        return departureDate;
    }

    public String getDepartureTime() {
        return departureTime;
    }

    public FlightDetails getFlight() {
        return flight;
    }

    public Integer getNoOfSeats() {
        return noOfSeats;
    }

    public BigDecimal getTotalFare() {
        return totalFare;
    }

    public UserDetails getUser() {
        return user;
    }

    public List<PassengerDetails> getPassengers() {
        return Collections.unmodifiableList(passengers);
    }
}
